# State machine validation rules for complaint status transitions

VALID_STATUSES = {
    "SUBMITTED", "AI_QUEUED", "AI_PROCESSING", "PENDING_VALIDATION", 
    "VERIFIED", "REJECTED", "ASSIGNMENT_PENDING", "ASSIGNED", 
    "IN_PROGRESS", "RESOLUTION_SUBMITTED", "RESOLUTION_REVIEW", 
    "RESOLVED", "REOPEN_REQUESTED", "REOPENED", "ESCALATED", "DUPLICATE",
    # 1.5 Legacy Support
    "REPORTED", "AI_ANALYSIS", "REPAIR_SUBMITTED"
}

ALLOWED_TRANSITIONS = {
    # 1.6 Strict Flows
    "SUBMITTED": ["AI_QUEUED", "ESCALATED"],
    "AI_QUEUED": ["AI_PROCESSING", "ESCALATED"],
    "AI_PROCESSING": ["VERIFIED", "PENDING_VALIDATION", "REJECTED", "DUPLICATE", "ESCALATED"],
    "PENDING_VALIDATION": ["VERIFIED", "REJECTED", "ESCALATED"],
    "VERIFIED": ["ASSIGNMENT_PENDING", "ASSIGNED", "ESCALATED"],
    "ASSIGNMENT_PENDING": ["ASSIGNED", "ESCALATED"],
    "ASSIGNED": ["IN_PROGRESS", "RESOLUTION_SUBMITTED", "RESOLVED", "ESCALATED"],
    "IN_PROGRESS": ["RESOLUTION_SUBMITTED", "RESOLVED", "ESCALATED"],
    "RESOLUTION_SUBMITTED": ["RESOLUTION_REVIEW", "RESOLVED", "REOPENED", "ESCALATED"],
    "RESOLUTION_REVIEW": ["RESOLVED", "REOPENED", "ESCALATED"],
    "RESOLVED": ["REOPEN_REQUESTED", "REOPENED", "ESCALATED"],
    "REOPEN_REQUESTED": ["REOPENED", "RESOLVED", "ESCALATED"],
    "REOPENED": ["ASSIGNMENT_PENDING", "ASSIGNED", "IN_PROGRESS", "ESCALATED"],
    "REJECTED": ["VERIFIED", "ESCALATED"],
    "DUPLICATE": ["ESCALATED"],
    "ESCALATED": ["RESOLVED"],
    
    # 1.5 Legacy Support Map
    "REPORTED": ["VERIFIED", "REJECTED", "AI_ANALYSIS", "ASSIGNED"],
    "AI_ANALYSIS": ["VERIFIED", "REJECTED", "ADMIN_REVIEW", "ASSIGNED", "COMMUNITY_VERIFY"],
    "REPAIR_SUBMITTED": ["RESOLVED", "REOPENED"]
}

def is_transition_allowed(from_status: str, to_status: str) -> bool:
    if from_status not in VALID_STATUSES or to_status not in VALID_STATUSES:
        return False
    if from_status == to_status:
        return True
    return to_status in ALLOWED_TRANSITIONS.get(from_status, [])
